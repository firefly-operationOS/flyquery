"""ASGI entry point for flyquery.

Loaded by ``flyquery serve`` and by ``uvicorn flyquery.main:app``.
Builds the :class:`PyFlyApplication`, scans every ``@rest_controller``,
``@configuration``, ``@service``, ``@command_handler`` and
``@query_handler`` under ``flyquery``, registers the RFC 7807
problem-detail handlers exposed by ``flyquery.web.conventions``, and
returns a FastAPI app with all routes mounted, the actuator + admin
exposed, and the OpenAPI spec generated by pyfly's introspector.
"""

from __future__ import annotations

from contextlib import asynccontextmanager
from typing import Any

from pyfly.core import PyFlyApplication
from pyfly.web.adapters.fastapi.app import create_app

from flyquery import __version__
from flyquery.app import FlyqueryApplication
from flyquery.web.conventions import (
    TenantContextMiddleware,
    register_exception_handlers,
)
from flyquery.web.openapi_headers import enrich_openapi_with_headers
from flyquery.web.openapi_override import install_openapi

_TITLE = "flyquery"
_DESCRIPTION = (
    "Operational Structured-Data Intelligence (upload-driven) -- "
    "multi-tenant ingestion + Text-to-SQL over user-uploaded "
    "structured files (CSV / TSV / XLSX / XLS / ODS / JSON / JSONL "
    "/ Parquet / Avro / ORC / Arrow / Feather + .gz/.zip/.bz2 "
    "variants). Materialises uploads to Parquet on object storage; "
    "indexes a long-lived schema knowledge base; answers natural-"
    "language questions via a multi-agent pipeline. Part of "
    "Firefly OperationOS."
)

# Build PyFlyApplication: loads pyfly.yaml, scans packages, prepares the
# DI context.
_pyfly = PyFlyApplication(FlyqueryApplication)


@asynccontextmanager
async def _lifespan(app: Any):
    """Drive the framework's startup / shutdown lifecycle.

    Also installs the pyfly-driven OpenAPI generator after startup, so
    Swagger / ReDoc see the real controller signatures (tags, request
    bodies, response models) instead of the lazy-resolution shim that
    pyfly registers with FastAPI.
    """
    # PyFlyApplication exposes route metadata + host/port via private
    # attributes that the framework's own lifespan flow writes to; we
    # mirror that here so pyfly's structured-logging "server_started"
    # event reports the right host/port.
    setattr(_pyfly, "_route_metadata", getattr(app.state, "pyfly_route_metadata", []))  # noqa: B010
    setattr(_pyfly, "_docs_enabled", getattr(app.state, "pyfly_docs_enabled", False))  # noqa: B010
    setattr(_pyfly, "_host", str(_pyfly.config.get("pyfly.web.host", "0.0.0.0")))  # noqa: B010
    setattr(_pyfly, "_port", int(_pyfly.config.get("pyfly.server.port", 8520)))  # noqa: B010
    await _pyfly.startup()
    # Re-scan HealthIndicator beans now that the container has built
    # every singleton (the eager scan inside ``create_app`` runs BEFORE
    # context startup and would otherwise miss every indicator wired
    # through @auto_configuration).
    rescan = getattr(app.state, "pyfly_install_health_indicators", None)
    if callable(rescan):
        rescan()
    install_openapi(
        app,
        _pyfly.context,
        title=_TITLE,
        version=__version__,
        description=_DESCRIPTION,
    )

    # Layer flyquery's tenant + workspace + agent-token + idempotency
    # headers on top of pyfly's spec. This is flyquery-specific and lives
    # in a sibling module (``openapi_headers``) so ``openapi_override.py``
    # stays byte-equivalent to the canon lockstep pin.
    #
    # The pyfly override caches its result in ``app.openapi_schema`` --
    # if anything called ``app.openapi()`` before this wrap was installed
    # (e.g. the actuator startup banner), the cached schema would be
    # served WITHOUT the headers. Clear the cache so the next ``openapi()``
    # call re-runs the underlying generator + our enrichment.
    _wrap_with_headers = app.openapi

    def _custom_openapi_with_headers():
        if getattr(app, "openapi_schema", None) is not None:
            return app.openapi_schema
        spec = _wrap_with_headers()
        enrich_openapi_with_headers(spec)
        app.openapi_schema = spec
        return spec

    app.openapi_schema = None  # invalidate any pre-wrap cached spec
    app.openapi = _custom_openapi_with_headers  # type: ignore[method-assign]
    yield
    await _pyfly.shutdown()


app = create_app(
    title=_TITLE,
    version=__version__,
    description=_DESCRIPTION,
    context=_pyfly.context,
    docs_enabled=True,
    actuator_enabled=True,
    lifespan=_lifespan,
)
# pyfly's FastAPI adapter only walks controller-LOCAL @exception_handler
# methods; the @controller_advice surface never fires. Register the
# conventions handler table directly with FastAPI so every
# FireflyHTTPException subclass + pydantic RequestValidationError lands
# on the canonical RFC 7807 envelope. The handler also unwraps
# CommandProcessingException so the typed domain exception raised by
# the service layer keeps its HTTP status + RFC 7807 code instead of
# being flattened to 400 COMMAND_PROCESSING_ERROR.
register_exception_handlers(app)
# Bind the request-scoped TenantContext from headers BEFORE any route
# (or DB session) runs. Pyfly's @rest_controller resolver bypasses
# FastAPI Depends, so require_tenant_context never fires for pyfly
# routes and tenant_context_from_request returns a ctx without binding
# the ContextVar. Without this middleware the SQLAlchemy after_begin
# hook (install_tenant_guc_hook) reads None and skips the SET LOCAL
# GUC writes -- every RLS-bound read through a non-BYPASSRLS role
# would then return zero rows. The middleware is added AFTER
# register_exception_handlers so the conventions ProblemDetail
# response shape covers anything the middleware leaks.
app.add_middleware(TenantContextMiddleware)
# The W3C correlation surface (X-Correlation-Id / X-Request-Id /
# X-Tenant-Id / traceparent / tracestate) is wired into pyfly's default
# WebFilter chain via
# ``pyfly.web.adapters.starlette.filters.CorrelationFilter`` -- no extra
# middleware to register here.
